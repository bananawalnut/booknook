#!/usr/bin/env python3
"""Publish schemas from Rust definitions; derive TS data types and a checksummed manifest."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
schemas = json.loads(subprocess.check_output(["cargo", "run", "--quiet", "--locked", "-p", "booknook-core", "--example", "schema"], cwd=ROOT))

def ts(schema):
    if schema is True:
        return "unknown"
    if schema is False:
        return "never"
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    for key in ["oneOf", "anyOf"]:
        if key in schema:
            return " | ".join("(" + ts(s) + ")" for s in schema[key])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    typ = schema.get("type")
    if isinstance(typ, list):
        return " | ".join(ts({**schema, "type": t}) for t in typ)
    if typ in ("integer", "number"):
        return "number"
    if typ in ("string", "boolean", "null"):
        return typ
    if typ == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(x) for x in schema["prefixItems"]) + "]"
        return "Array<" + ts(schema.get("items", {})) + ">"
    if typ == "object":
        props = schema.get("properties", {})
        if not props:
            additional = schema.get("additionalProperties", {})
            return "Record<string, " + (ts(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = schema.get("required", [])
        return "{ " + "; ".join(json.dumps(k) + ("" if k in required else "?") + ": " + ts(v) for k, v in props.items()) + " }"
    return "unknown"

outputs = {}
PROVIDER_SCHEMAS = {"provider-registry", "provider-operation", "provider-request", "provider-response", "provider-execution"}
PORTABLE_SCHEMAS = {"portable-export", "social-archive"}
for name, schema in schemas.items():
    if name in PORTABLE_SCHEMAS:
        schema["$id"] = f"urn:booknook:schema:{name}:v2"
        directory = "ontology/portable/v2"
    elif name in PROVIDER_SCHEMAS:
        schema["$id"] = f"urn:booknook:schema:{name}:v1"
        directory = "ontology/providers/v1"
    else:
        schema["$id"] = {
            "castalia-provider-connection": "urn:castalia:schema:provider-connection:v1",
            "castalia-native-authority-profile": "urn:castalia:schema:native-authority-profile:v1",
        }.get(name, f"urn:booknook:schema:0.3.0:{name}")
        directory = "ontology/v0.3.0"
    outputs[ROOT / f"{directory}/{name}.schema.json"] = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"

def typed_module(names, output):
    definitions = {}
    for name in names:
        definitions.update(schemas[name].get("$defs", {}))
    lines = ["// SPDX-License-Identifier: MIT OR Apache-2.0", "// Generated by scripts/generate-contracts.py; do not edit."]
    for name, definition in sorted(definitions.items()):
        if name not in names.values():
            lines.append(f"export type {name} = {ts(definition)};")
    for name, typename in names.items():
        lines.append(f"export type {typename} = {ts(schemas[name])};")
    outputs[ROOT / output] = "\n".join(lines) + "\n"

typed_module({"state": "State", "command": "Command", "connections": "Connections", "castalia-provider-connection": "ProviderConnection", "castalia-native-authority-profile": "NativeAuthorityProfile", "identity": "AttributionLink", "audio-observation": "AudioObservation", "audio-candidates": "AudioEditionCandidates"}, "sdk/typescript/types.ts")
typed_module({"social": "SocialState", "social-action": "SocialAction", "social-local": "LocalSocialCommand", "social-event": "SocialEvent", "publication": "ApprovedPublication", "authority-policy": "AuthorityPolicy"}, "sdk/typescript/social-types.ts")

typed_module({"provider-registry": "ProviderRegistry", "provider-operation": "ProviderOperation", "provider-request": "ProviderRequest", "provider-response": "ProviderResponse", "provider-execution": "ProviderExecution"}, "sdk/typescript/provider-types.ts")

typed_module({"portable-export": "PortableArchive", "social-archive": "SocialArchiveBundle"}, "sdk/typescript/archive-types.ts")

for path, content in outputs.items():
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Generated contract is stale: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

release = ROOT / "ontology/v0.3.0"
manifest = {
    "schema": "booknook.ontology-manifest.v1", "version": "0.3.0", "namespace": "urn:booknook:ontology:",
    "castalia": {"version": "0.6.0", "canonical_base_url": "https://zenith-research.ca/ontology/v0.6.0", "bundle_digest": "11d670a57b2052b4de00509559d081b524bf953c6da2544a25f33976857f8f4f"},
    "artifacts": [{"path": p.name, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(release.iterdir()) if p.is_file() and p.name != "manifest.json"]
}
raw = json.dumps(manifest, indent=2) + "\n"
path = release / "manifest.json"
if "--check" in sys.argv:
    if path.read_text() != raw:
        raise SystemExit("Ontology manifest is stale")
else:
    path.write_text(raw)
provider_release = ROOT / "ontology/providers/v1"
provider_manifest = {
    "schema": "booknook.provider-contract-manifest.v1", "version": "1", "namespace": "urn:booknook:schema:",
    "artifacts": [{"path": p.name, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(provider_release.iterdir()) if p.is_file() and p.name != "manifest.json"]
}
provider_raw = json.dumps(provider_manifest, indent=2) + "\n"
provider_manifest_path = provider_release / "manifest.json"
if "--check" in sys.argv:
    if provider_manifest_path.read_text() != provider_raw:
        raise SystemExit("Provider contract manifest is stale")
else:
    provider_manifest_path.write_text(provider_raw)
portable_release = ROOT / "ontology/portable/v2"
portable_manifest = {
    "schema": "booknook.portable-contract-manifest.v1", "version": "2", "namespace": "urn:booknook:schema:",
    "artifacts": [{"path": p.name, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(portable_release.iterdir()) if p.is_file() and p.name != "manifest.json"]
}
portable_raw = json.dumps(portable_manifest, indent=2) + "\n"
portable_manifest_path = portable_release / "manifest.json"
if "--check" in sys.argv:
    if portable_manifest_path.read_text() != portable_raw:
        raise SystemExit("Portable contract manifest is stale")
else:
    portable_manifest_path.write_text(portable_raw)
print("Contracts and manifests verified." if "--check" in sys.argv else "Contracts and manifests generated.")
